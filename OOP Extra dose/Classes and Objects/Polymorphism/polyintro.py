# """📘 Polymorphism — Clean Notes
# Meaning
# - Poly = many
# - Morphe = forms
# - Polymorphism = One thing behaving in many forms
# Example
# - 5 + 5 = 10
# - '5' + '5' = '55'
# Same operator, different behavior → polymorphism.

# 🧩 Types of Polymorphism in Python
# 1. Duck Typing (Python Philosophy)
# - “If it walks like a duck and quacks like a duck, it’s a duck.”
# - Python cares about behavior, not type.

# 2. Overloading
# Python does not support traditional overloading, but we simulate it.
# a. Operator Overloading
# - Using special methods like __add__, __mul__, etc.
# b. Method Overloading
# - Python does not support it directly.
# - Achieved using default arguments or *args.
# c. Constructor Overloading
# - Not supported directly.
# - Achieved using default parameters.

# 3. Overriding
# a. Method Overriding
# - Child class provides its own version of a parent method.
# b. Constructor Overriding
# - Child class defines its own __init__().
# - Parent constructor must be called manually using super().

# 🐍 Pythonic Behavior
# Duck Typing
# - Focus on what an object can do, not what it is.
# EAFP (Easier to Ask Forgiveness than Permission)
# - Try the operation.
# - Handle exceptions if something goes wrong.
# - Pythonic style.
# LBYL (Look Before You Leap)
# - Check conditions before performing an operation.
# - Less Pythonic, more common in languages like Java/C++.


